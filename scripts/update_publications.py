#!/usr/bin/env python3

import json
import urllib.parse
import urllib.request
from collections import defaultdict
from pathlib import Path

ORCID = "0000-0003-2591-7379"

OUTPUT = Path("research/publications.md")
OVERRIDES = Path("research/publications-overrides.json")

TYPE_LABELS = {
    "article": "Journal articles and reviews",
    "review": "Journal articles and reviews",
    "editorial": "Editorials and commentaries",
    "letter": "Editorials and commentaries",
    "book-chapter": "Book chapters",
    "book": "Books",
    "preprint": "Preprints",
}

SECTION_ORDER = [
    "Journal articles and reviews",
    "Editorials and commentaries",
    "Book chapters",
    "Books",
    "Preprints",
    "Other scholarly works",
]


def get_json(url):
    request = urllib.request.Request(
        url,
        headers={
            "User-Agent":
            "gliosis-publications/1.0"
        },
    )

    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def authors(work):
    names = []

    for authorship in work.get("authorships", []):
        author = authorship.get("author") or {}
        name = author.get("display_name")

        if name:
            names.append(name)

    return ", ".join(names)


def journal(work):
    location = work.get("primary_location") or {}
    source = location.get("source") or {}

    return source.get("display_name") or ""


def strip_prefix(value, prefix):
    if not value:
        return None

    return value.removeprefix(prefix)


def citation(work):
    author_text = authors(work)
    title = work.get("display_name") or "Untitled"
    journal_text = journal(work)

    year = work.get("publication_year")

    bibliography = work.get("biblio") or {}

    volume = bibliography.get("volume")
    issue = bibliography.get("issue")
    first_page = bibliography.get("first_page")
    last_page = bibliography.get("last_page")

    parts = []

    if author_text:
        parts.append(f"**{author_text}.**")

    parts.append(f"“{title}.”")

    if journal_text:
        parts.append(f"*{journal_text}*.")

    details = []

    if year:
        details.append(str(year))

    if volume:
        volume_text = str(volume)

        if issue:
            volume_text += f"({issue})"

        details.append(volume_text)

    if first_page:
        pages = str(first_page)

        if last_page and last_page != first_page:
            pages += f"–{last_page}"

        details.append(pages)

    if details:
        parts.append("; ".join(details) + ".")

    links = []

    doi = strip_prefix(
        work.get("doi"),
        "https://doi.org/"
    )

    pmid = strip_prefix(
        (work.get("ids") or {}).get("pmid"),
        "https://pubmed.ncbi.nlm.nih.gov/"
    )

    if doi:
        links.append(
            f"[DOI](https://doi.org/{doi})"
        )

    if pmid:
        pmid = pmid.rstrip("/")

        links.append(
            f"[PMID](https://pubmed.ncbi.nlm.nih.gov/{pmid}/)"
        )

    if links:
        parts.append(" · ".join(links))

    return " ".join(parts)


def main():

    overrides = {
        "exclude_openalex_ids": []
    }

    if OVERRIDES.exists():
        overrides.update(
            json.loads(
                OVERRIDES.read_text(
                    encoding="utf-8"
                )
            )
        )

    excluded = set(
        overrides.get(
            "exclude_openalex_ids",
            []
        )
    )

    params = {
        "filter":
        f"authorships.author.orcid:{ORCID}",
        "per-page": "100",
        "sort":
        "publication_date:desc",
    }

    url = (
        "https://api.openalex.org/works?"
        + urllib.parse.urlencode(params)
    )

    data = get_json(url)

    works = []

    for work in data.get("results", []):

        openalex_id = (
            work.get("id") or ""
        ).split("/")[-1]

        if openalex_id not in excluded:
            works.append(work)

    grouped = defaultdict(
        lambda: defaultdict(list)
    )

    for work in works:

        year = (
            work.get("publication_year")
            or "Undated"
        )

        section = TYPE_LABELS.get(
            work.get("type"),
            "Other scholarly works"
        )

        grouped[section][year].append(work)

    lines = [
        "---",
        "layout: page",
        "title: Publications",
        "permalink: /research/publications/",
        "---",
        "",
        "A bibliography of my published scholarly work.",
        "",
        f"**ORCID:** [{ORCID}](https://orcid.org/{ORCID})",
        "",
        "<!-- Generated automatically. Do not edit this file directly. -->",
        "",
    ]

    for section in SECTION_ORDER:

        if section not in grouped:
            continue

        lines.append(f"## {section}")
        lines.append("")

        years = sorted(
            grouped[section].keys(),
            key=lambda x: (
                x == "Undated",
                x
            ),
            reverse=True,
        )

        for year in years:

            lines.append(f"### {year}")
            lines.append("")

            for work in grouped[section][year]:

                lines.append(
                    citation(work)
                )

                lines.append("")

    OUTPUT.write_text(
        "\n".join(lines).rstrip()
        + "\n",
        encoding="utf-8",
    )

    print(
        f"Wrote {len(works)} works "
        f"to {OUTPUT}"
    )


if __name__ == "__main__":
    main()
